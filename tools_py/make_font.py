ACC = {
    'acute': ["...#.", "..#.."],
    'tilde': [".##.#", "#..#."],
    'diaer': [".....", ".#.#."],
}
def accented(base, kind):
    rows = G[base]
    w = len(rows[0])
    acc = ACC[kind]
    if w == 3:
        acc = {"acute": ["..#", ".#."], "tilde": [".#.", "#.#"], "diaer": ["...", "#.#"]}[kind]
    return acc, rows
ACCENTED = {'Á':('A','acute'),'É':('E','acute'),'Í':('I','acute'),'Ó':('O','acute'),
            'Ú':('U','acute'),'Ñ':('N','tilde'),'Ü':('U','diaer')}

CHARSET = list(G.keys()) + list(ACCENTED.keys())
CELL_W, CELL_H = 7, 11

def glyph_pixels(ch):
    """Devuelve (lista de (x,y) relativos, ancho) con y en [-2..6]."""
    if ch in ACCENTED:
        base, kind = ACCENTED[ch]
        acc, rows = accented(base, kind)
        w = len(rows[0])
        px = []
        for r, line in enumerate(rows):
            for c, v in enumerate(line):
                if v == '#': px.append((c, r))
        for r, line in enumerate(acc):
            for c, v in enumerate(line):
                if v == '#': px.append((c, r - 2))
        return px, w
    rows = G[ch]
    w = len(rows[0])
    px = [(c, r) for r, line in enumerate(rows) for c, v in enumerate(line) if v == '#']
    return px, w

n = len(CHARSET)
fill = Image.new('RGBA', (n * CELL_W, CELL_H), (0, 0, 0, 0))
outl = Image.new('RGBA', (n * CELL_W, CELL_H), (0, 0, 0, 0))
widths = []
for i, ch in enumerate(CHARSET):
    px, w = glyph_pixels(ch)
    widths.append(w)
    for (x, y) in px:
        ax, ay = i * CELL_W + 1 + x, 1 + (y + 2)
        fill.putpixel((ax, ay), (255, 255, 255, 255))
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                bx, by = ax + dx, ay + dy
                if 0 <= by < CELL_H and i * CELL_W <= bx < (i + 1) * CELL_W:
                    outl.putpixel((bx, by), (255, 255, 255, 255))
os.makedirs('assets/fonts', exist_ok=True)
fill.save('assets/fonts/font_fill.png')
outl.save('assets/fonts/font_outline.png')

charset_str = ''.join(CHARSET).replace('\\', '\\\\').replace('"', '\\"')
with open('scripts/ui/pixel_font_data.gd', 'w', encoding='utf-8') as f:
    f.write('extends RefCounted\n')
    f.write('## Datos generados por tools_py/make_font.py. No editar a mano.\n\n')
    f.write('const CHARSET := "%s"\n' % charset_str)
    f.write('const WIDTHS := %s\n' % str(widths))
    f.write('const CELL_W := %d\nconst CELL_H := %d\n' % (CELL_W, CELL_H))
